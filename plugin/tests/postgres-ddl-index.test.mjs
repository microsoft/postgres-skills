test("identity columns are implicitly non-null while ordinary generated columns remain nullable", () => {
  const { objects } = parsePostgresDdl(`
    CREATE TABLE public.t (
      always_id integer GENERATED ALWAYS AS IDENTITY,
      default_id integer GENERATED BY DEFAULT AS IDENTITY,
      generated_value integer GENERATED ALWAYS AS (always_id + 1) STORED,
      plain_value integer
    );
  `);

  assert.deepEqual(objects[0].columns.map((column) => column.nullable), [false, false, true, true]);
  assert.ok(objects[0].columns.slice(0, 3).every((column) => column.hasDefault));
});

test("indexes a schema-only dump, quoted names, columns, and separate constraints without bodies", async () => {
  const root = await fixture({
    "dump.sql": `
      \\restrict dump_guard
      SET search_path = "App", pg_catalog;
      CREATE TABLE "Task" (
        "Id" bigint,
        status character varying(20) NOT NULL DEFAULT 'PRIVATE_VALUE',
        amount numeric(12, 2),
        parent_id bigint REFERENCES "App"."Task"("Id")
      );
      ALTER TABLE ONLY "App"."Task" ADD CONSTRAINT task_pk PRIMARY KEY ("Id");
      CREATE SEQUENCE "App".task_seq;
      CREATE VIEW "App".task_view AS SELECT "Id" FROM "App"."Task";
      CREATE FUNCTION "App".find_task(p_id bigint, OUT status text)
        RETURNS text LANGUAGE plpgsql AS $body$
        BEGIN
          -- CREATE TABLE do_not_index(x int);
          RETURN 'PRIVATE_FUNCTION_BODY';
        END;
        $body$;
      CREATE TYPE "App".task_state AS ENUM ('PRIVATE_ENUM_VALUE');
      CREATE DOMAIN "App".task_amount AS numeric(12, 2) NOT NULL;
      CREATE INDEX task_status_idx ON "App"."Task" (status);
      CREATE TRIGGER task_changed AFTER UPDATE ON "App"."Task"
        FOR EACH ROW EXECUTE FUNCTION "App".changed();
      \\unrestrict dump_guard
    `,
  });
  try {
    const index = await indexPostgresDdlFolder(root);
    assert.equal(index.evidenceKind, "offline-postgresql-ddl-snapshot");
    assert.equal(index.liveTargetVerified, false);
    assert.equal(index.absenceMeans, "not-found-in-supplied-snapshot");
    assert.deepEqual(index.objects.map((object) => object.kind).sort(),
      ["domain", "function", "index", "sequence", "table", "trigger", "type", "view"]);
    const table = index.objects.find((object) => object.kind === "table");
    assert.equal(table.schema, "App");
    assert.equal(table.name, "Task");
    assert.deepEqual(table.columns[0], { name: "Id", type: "bigint", nullable: false, hasDefault: false });
    assert.equal(table.columns[1].type, "character varying(20)");
    assert.equal(table.columns[1].nullable, false);
    assert.equal(table.columns[1].hasDefault, true);
    assert.equal(table.columns[2].type, "numeric(12,2)");
    assert.ok(table.constraints.some((entry) => entry.kind === "foreign-key"));
    assert.ok(table.constraints.some((entry) => entry.kind === "primary-key" && entry.name === "task_pk"));
    const routine = index.objects.find((object) => object.kind === "function");
    assert.deepEqual(routine.identityArguments, ["bigint"]);
    assert.equal(routine.arguments[1].mode, "out");
    assert.equal(routine.returns, "text");
    assert.equal(routine.bodyPresent, true);
    assert.equal(index.objects.find((object) => object.kind === "domain").baseType, "numeric(12,2)");
    assert.equal(index.objects.find((object) => object.kind === "index").schema, "App");
    assert.match(index.files[0].sha256, /^[a-f0-9]{64}$/);
    assert.match(index.snapshotSha256, /^[a-f0-9]{64}$/);
    assert.doesNotMatch(JSON.stringify(index), /PRIVATE_|do_not_index|dump_guard/);
    assert.doesNotMatch(JSON.stringify(index), new RegExp(root.replaceAll("\\", "\\\\")));
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("routine overloads, defaults, modes, type aliases, and schema ambiguity remain explicit", async () => {
  const root = await fixture({
    "routines.sql": `
      CREATE FUNCTION app.lookup(integer) RETURNS text AS $$ SELECT 'one' $$ LANGUAGE sql;
      CREATE FUNCTION app.lookup(p_name text DEFAULT 'PRIVATE_DEFAULT') RETURNS text AS 'SELECT $1' LANGUAGE sql;
      CREATE FUNCTION other.lookup(IN id int8, INOUT value text) RETURNS text AS $$ SELECT value $$ LANGUAGE sql;
      CREATE PROCEDURE app.update_task(IN id bigint, INOUT value text) LANGUAGE plpgsql AS $$ BEGIN NULL; END; $$;
    `,
  });
  try {
    const index = await indexPostgresDdlFolder(root);
    const matches = matchPostgresObjects(index, [
      { kind: "routine", schema: "app", name: "lookup" },
      { kind: "routine", schema: "app", name: "lookup", identityArguments: ["int4"] },
      { kind: "routine", schema: null, name: "lookup" },
      { kind: "relation", schema: "app", name: "missing" },
    ]);
    assert.equal(matches[0].status, "ambiguous");
    assert.equal(matches[0].candidates.length, 2);
    assert.equal(matches[1].status, "snapshot-candidate");
    assert.equal(matches[1].candidates[0].arguments[0].name, null);
    assert.equal(matches[2].candidates.length, 3);
    assert.equal(matches[3].status, "not-found-in-supplied-snapshot");
    assert.equal(matchPostgresObjects(null, [{ kind: "relation", name: "task" }])[0].status, "not-supplied");
    const routine = index.objects.find((object) => object.kind === "procedure");
    assert.deepEqual(routine.identityArguments, ["bigint", "text"]);
    assert.doesNotMatch(JSON.stringify(index), /PRIVATE_DEFAULT/);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("does not infer a schema from filenames or silently fold quoted identifiers", () => {
  const parsed = parsePostgresDdl(`
    CREATE TABLE "MixedCase" (id integer);
    CREATE TABLE mixedcase (id integer);
    CREATE TABLE "schema.with.dot"."name.with.dot" ("quoted""column" integer);
  `);
  assert.equal(parsed.objects[0].schema, null);
  assert.equal(parsed.objects[0].name, "MixedCase");
  assert.equal(parsed.objects[1].name, "mixedcase");
  assert.equal(parsed.objects[2].schema, "schema.with.dot");
  assert.equal(parsed.objects[2].columns[0].name, 'quoted"column');
  const unresolved = matchPostgresObjects({ objects: [parsed.objects[0]] },
    [{ kind: "relation", schema: "app", name: "MixedCase" }])[0];
  assert.equal(unresolved.status, "ambiguous");
  assert.equal(unresolved.candidates.length, 1);
});

test("literal punctuation does not split arguments or change quoted type identities", () => {
  const parsed = parsePostgresDdl(`
    CREATE FUNCTION app.f(p text DEFAULT '(', q integer DEFAULT 1)
      RETURNS text AS $$SELECT p$$ LANGUAGE sql;
    CREATE FUNCTION app.g(p text DEFAULT ')') RETURNS text LANGUAGE sql;
    CREATE INDEX CONCURRENTLY task_idx ON app.task(id);
  `);
  assert.deepEqual(parsed.objects[0].identityArguments, ["text", "integer"]);
  assert.equal(parsed.objects[1].bodyPresent, false);
  assert.equal(parsed.objects[2].name, "task_idx");
  assert.equal(normalizePgType('app."type(12)"'), 'app."type(12)"');
  assert.equal(normalizePgType('app."type . (12), value"'), 'app."type . (12), value"');
  assert.equal(normalizePgType("pg_catalog.int4[4][]"), "integer[]");
  assert.equal(normalizePgType("numeric(12,2)"), "numeric");
  assert.throws(() => parsePostgresDdl('CREATE TABLE app."" (id int);'), /identifier cannot be empty/);
  assert.throws(() => parsePostgresDdl("CREATE TABLE app.t(id int, id text);"), /duplicate column/);
});

test("comments, escaped literals, and dollar bodies cannot introduce phantom DDL", () => {
  const parsed = parsePostgresDdl(`
    /* nested /* CREATE TABLE fake_one(x int); */ comment */
    -- CREATE TABLE fake_two(x int);
    CREATE FUNCTION app.f() RETURNS text
      LANGUAGE sql AS $tag$ SELECT 'CREATE TABLE fake_three(x int);' $tag$;
    COMMENT ON FUNCTION app.f() IS E'not a quote: \\' CREATE TABLE fake_four(x int);';
    CREATE TABLE app.real_table (id integer);
  `);
  assert.deepEqual(parsed.objects.map((object) => object.name), ["f", "real_table"]);
  assert.throws(() => parsePostgresDdl("CREATE FUNCTION f() RETURNS text AS $$unterminated"), /Unterminated/);
  assert.throws(() => tokenizeSql("/* unfinished"), /Unterminated/);
  assert.throws(() => tokenizeSql("'unfinished"), /Unterminated/);
  assert.throws(() => tokenizeSql("CREATE TABLE x(id int)", { maxTokens: 2 }), /token budget/);
});

test("uninterpreted definitions and alterations are disclosed rather than treated as complete contracts", async () => {
  const root = await fixture({
    "objects.sql": `
      CREATE TABLE app.task (id integer);
      ALTER TABLE app.task ALTER COLUMN id TYPE bigint;
      CREATE POLICY task_policy ON app.task USING (true);
      CREATE TABLE app.copy AS SELECT id FROM app.task;
    `,
  });
  try {
    const index = await indexPostgresDdlFolder(root);
    assert.equal(index.status, "PARTIAL");
    assert.equal(index.limitations.length, 2);
    assert.ok(index.objects.find((object) => object.name === "task").limitations.length);
    assert.ok(index.objects.find((object) => object.name === "copy").limitations.length);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("rejects duplicate identities including routine type-alias collisions", async () => {
  for (const sql of [
    "CREATE TABLE app.task(id int); CREATE TABLE app.task(id int);",
    "CREATE FUNCTION app.f(int4) RETURNS int AS $$SELECT 1$$ LANGUAGE sql; CREATE FUNCTION app.f(integer) RETURNS int AS $$SELECT 1$$ LANGUAGE sql;",
  ]) {
    const root = await fixture({ "duplicate.sql": sql });
    try {
      await assert.rejects(indexPostgresDdlFolder(root), /duplicate or ambiguous/);
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  }
});

test("rejects data dumps, SQL client commands, and non-DDL folders without executing SQL", async () => {
  for (const sql of [
    "\\connect production\nCREATE TABLE app.task(id int);",
    "\\i secret.sql\nCREATE TABLE app.task(id int);",
    "CREATE TABLE app.task(id int); INSERT INTO app.task VALUES(1);",
    "CREATE TABLE app.task(id int); COPY app.task FROM stdin;",
  ]) {
    const root = await fixture({ "input.sql": sql });
    try {
      await assert.rejects(indexPostgresDdlFolder(root), /SQL client commands|schema-only/);
    } finally {
      await rm(root, { recursive: true, force: true });
    }
  }
  const root = await fixture({ "App.java": "class App {}", "schema.sql": "CREATE TABLE app.task(id int);" });
  try {
    await assert.rejects(indexPostgresDdlFolder(root), /dedicated schema-only export/);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("validates missing, empty, oversized, non-UTF-8, and cancelled snapshot inputs", async () => {
  const root = await fixture({ "README.md": "An empty export." });
  try {
    await assert.rejects(indexPostgresDdlFolder(path.join(root, "missing")), /required path is unavailable/i);
    await assert.rejects(indexPostgresDdlFolder(root), /no supported DDL files/);
    await writeFile(path.join(root, "schema.sql"), "CREATE TABLE app.task(id int);");
    await assert.rejects(indexPostgresDdlFolder(root, { maxFileBytes: 4 }), /at most 4 bytes/);
    await assert.rejects(indexPostgresDdlFolder(root, { maxTotalBytes: 4 }), /at most 4 bytes/);
    await assert.rejects(indexPostgresDdlFolder(root, { maxEntries: 1 }), /entry limit/);
    await writeFile(path.join(root, "schema.sql"), Buffer.from([0xff, 0xfe]));
    await assert.rejects(indexPostgresDdlFolder(root), /UTF-8/);
    const controller = new AbortController();
    controller.abort();
    await assert.rejects(indexPostgresDdlFolder(root, { signal: controller.signal }), /cancelled/);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});

test("rejects linked DDL files and leaves the source snapshot untouched", async (context) => {
  const root = await fixture({ "schema.sql": "CREATE TABLE app.task(id int);" });
  try {
    const before = await readFile(path.join(root, "schema.sql"));
    try {
      await symlink(path.join(root, "schema.sql"), path.join(root, "linked.sql"), "file");
    } catch (error) {
      if (["EPERM", "EACCES"].includes(error.code)) {
        context.skip("The operating system does not permit this test to create a symbolic link.");
        return;
      }
      throw error;
    }
    await assert.rejects(indexPostgresDdlFolder(root), /Filesystem links/);
    assert.deepEqual(await readFile(path.join(root, "schema.sql")), before);
  } finally {
    await rm(root, { recursive: true, force: true });
  }
});
